/**
 * Generates platform token files from src/tokens.ts.
 * Run: pnpm --filter @jarvis/tokens build
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokens, type ThemeName } from '../src/tokens';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const repo = resolve(root, '../..');
const banner = 'GENERATED by packages/tokens/scripts/build.ts — do not edit by hand.';

const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

function write(path: string, content: string) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log('wrote', path.replace(repo + '/', ''));
}

// ---------- CSS ----------
function cssColors(theme: ThemeName) {
  const c = tokens.color[theme];
  const e = tokens.elevation[theme];
  return [
    ...Object.entries(c).map(([k, v]) => `  --color-${kebab(k)}: ${v};`),
    `  --shadow-popover: ${e.popover};`,
    `  --shadow-sheet: ${e.sheet};`,
    `  color-scheme: ${theme};`,
  ].join('\n');
}

function css() {
  const lines: string[] = [`/* ${banner} */`, ':root {'];
  for (const [k, v] of Object.entries(tokens.space)) lines.push(`  --space-${k}: ${v / 16}rem;`);
  for (const [k, v] of Object.entries(tokens.radius)) lines.push(`  --radius-${k}: ${v}px;`);
  lines.push(`  --font-sans: ${tokens.font.sans};`);
  lines.push(`  --font-sans-arabic: ${tokens.font.sansArabic};`);
  lines.push(`  --font-mono: ${tokens.font.mono};`);
  for (const [k, t] of Object.entries(tokens.type)) {
    const n = kebab(k);
    lines.push(`  --type-${n}-size: ${t.size / 16}rem;`);
    lines.push(`  --type-${n}-line: ${t.lineHeight / 16}rem;`);
    lines.push(`  --type-${n}-weight: ${t.weight};`);
    lines.push(`  --type-${n}-tracking: ${t.tracking}em;`);
  }
  for (const [k, v] of Object.entries(tokens.motion.duration))
    lines.push(`  --duration-${k}: ${v}ms;`);
  for (const [k, v] of Object.entries(tokens.motion.easing)) lines.push(`  --ease-${k}: ${v};`);
  lines.push(`  --presence-rotation: ${tokens.motion.presenceRotationMs}ms;`);
  lines.push(`  --sidebar-width: ${tokens.layout.sidebarWidth}px;`);
  lines.push(`  --content-max: ${tokens.layout.contentMaxWidth}px;`);
  lines.push(`  --content-wide-max: ${tokens.layout.wideContentMaxWidth}px;`);
  lines.push(`  --touch-min: ${tokens.layout.minTouchTarget}px;`);
  for (const [k, v] of Object.entries(tokens.layout.controlHeight))
    lines.push(`  --control-${k}: ${v}px;`);
  lines.push(`  --focus-width: ${tokens.focus.width}px;`);
  lines.push(`  --focus-offset: ${tokens.focus.offset}px;`);
  lines.push('}', '');
  // Light is the default; explicit data-theme wins over the OS preference.
  lines.push(`:root,\n:root[data-theme='light'] {\n${cssColors('light')}\n}`, '');
  lines.push(
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n${cssColors('dark').replace(/^/gm, '  ')}\n  }\n}`,
    '',
  );
  lines.push(`:root[data-theme='dark'] {\n${cssColors('dark')}\n}`, '');
  lines.push(
    `@media (prefers-reduced-motion: reduce) {\n  :root {\n${Object.keys(tokens.motion.duration)
      .map((k) => `    --duration-${k}: 0ms;`)
      .join('\n')}\n  }\n}`,
    '',
  );
  return lines.join('\n');
}

// ---------- Swift ----------
function swiftColor(hex: string) {
  if (hex.startsWith('rgba')) {
    const [r, g, b, a] = hex.match(/[\d.]+/g)!.map(Number);
    return `Color(.sRGB, red: ${(r! / 255).toFixed(3)}, green: ${(g! / 255).toFixed(3)}, blue: ${(b! / 255).toFixed(3)}, opacity: ${a})`;
  }
  return `Color(hex: 0x${hex.slice(1)})`;
}

function swift() {
  const keys = Object.keys(tokens.color.light) as (keyof typeof tokens.color.light)[];
  const colorLines = keys
    .map(
      (k) =>
        `    static let ${k} = Color.adaptive(light: ${swiftColor(tokens.color.light[k])}, dark: ${swiftColor(tokens.color.dark[k])})`,
    )
    .join('\n');
  const spaceLines = Object.entries(tokens.space)
    .map(([k, v]) => `    static let s${k}: CGFloat = ${v}`)
    .join('\n');
  const radiusLines = Object.entries(tokens.radius)
    .map(([k, v]) => `    static let ${k}: CGFloat = ${v === 9999 ? 999 : v}`)
    .join('\n');
  const typeLines = Object.entries(tokens.type)
    .map(
      ([k, t]) =>
        `    static let ${k} = TypeStyle(size: ${t.size}, lineHeight: ${t.lineHeight}, weight: .${t.weight === 600 ? 'semibold' : t.weight === 500 ? 'medium' : 'regular'}, tracking: ${t.tracking})`,
    )
    .join('\n');
  const durLines = Object.entries(tokens.motion.duration)
    .map(([k, v]) => `    static let ${k}: Double = ${v / 1000}`)
    .join('\n');
  return `// ${banner}
import SwiftUI

enum MeridianColor {
${colorLines}
}

enum MeridianSpace {
${spaceLines}
}

enum MeridianRadius {
${radiusLines}
}

struct TypeStyle {
    let size: CGFloat
    let lineHeight: CGFloat
    let weight: Font.Weight
    let tracking: CGFloat
}

enum MeridianType {
${typeLines}
}

enum MeridianMotion {
${durLines}
    static let presenceRotation: Double = ${tokens.motion.presenceRotationMs / 1000}
}

enum MeridianLayout {
    static let minTouchTarget: CGFloat = ${tokens.layout.minTouchTarget}
    static let contentMaxWidth: CGFloat = ${tokens.layout.contentMaxWidth}
}
`;
}

// ---------- Kotlin ----------
function kotlin() {
  const keys = Object.keys(tokens.color.light) as (keyof typeof tokens.color.light)[];
  const kColor = (v: string) => {
    if (v.startsWith('rgba')) {
      const [r, g, b, a] = v.match(/[\d.]+/g)!.map(Number);
      return `Color(red = ${r}, green = ${g}, blue = ${b}, alpha = ${Math.round(a! * 255)})`;
    }
    return `Color(0xFF${v.slice(1)})`;
  };
  const scheme = (t: ThemeName) =>
    keys.map((k) => `        ${k} = ${kColor(tokens.color[t][k])},`).join('\n');
  return `// ${banner}
package ai.jarvis.designsystem

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

data class MeridianColors(
${keys.map((k) => `    val ${k}: Color,`).join('\n')}
)

object MeridianTokens {
    val Light = MeridianColors(
${scheme('light')}
    )
    val Dark = MeridianColors(
${scheme('dark')}
    )
${Object.entries(tokens.space)
  .map(([k, v]) => `    val Space${k} = ${v}.dp`)
  .join('\n')}
${Object.entries(tokens.radius)
  .map(([k, v]) => `    val Radius${k[0]!.toUpperCase() + k.slice(1)} = ${v === 9999 ? 999 : v}.dp`)
  .join('\n')}
${Object.entries(tokens.type)
  .map(([k, t]) => `    val Type${k[0]!.toUpperCase() + k.slice(1)}Size = ${t.size}.sp`)
  .join('\n')}
}
`;
}

write(resolve(root, 'generated/tokens.css'), css());
write(resolve(root, 'generated/tokens.json'), JSON.stringify(tokens, null, 2) + '\n');
write(resolve(root, 'generated/Tokens.kt'), kotlin());
write(resolve(repo, 'apps/ios/Jarvis/DesignSystem/Tokens.swift'), swift());
