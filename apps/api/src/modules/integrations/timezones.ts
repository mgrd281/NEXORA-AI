/**
 * Time-zone arithmetic for calendars (docs/architecture/phase-c.md §3.3).
 * Instants are UTC everywhere; local times are computed IN the zone with
 * Intl (DST-correct), never by adding hours to UTC.
 */

export interface LocalParts {
  year: number;
  month: number; // 1–12
  day: number;
  hour: number;
  minute: number;
  second: number;
  /** 0 = Sunday … 6 = Saturday. */
  weekday: number;
}

const WEEKDAYS: Record<string, number> = { Sun: 0, Mon: 1, Tue: 2, Wed: 3, Thu: 4, Fri: 5, Sat: 6 };
const formatters = new Map<string, Intl.DateTimeFormat>();

function formatter(tz: string): Intl.DateTimeFormat {
  let f = formatters.get(tz);
  if (!f) {
    f = new Intl.DateTimeFormat('en-US', {
      timeZone: tz,
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
      weekday: 'short',
      hourCycle: 'h23',
    });
    formatters.set(tz, f);
  }
  return f;
}

/** The wall-clock parts of an instant in `tz`. */
export function localParts(at: Date | number, tz: string): LocalParts {
  const parts = Object.fromEntries(
    formatter(tz)
      .formatToParts(new Date(at))
      .map((p) => [p.type, p.value]),
  ) as Record<string, string>;
  return {
    year: Number(parts.year),
    month: Number(parts.month),
    day: Number(parts.day),
    hour: Number(parts.hour) % 24,
    minute: Number(parts.minute),
    second: Number(parts.second),
    weekday: WEEKDAYS[parts.weekday ?? 'Sun'] ?? 0,
  };
}

/** Offset of `tz` from UTC at an instant, in milliseconds (local − UTC). */
export function zoneOffsetMs(at: number, tz: string): number {
  const p = localParts(at, tz);
  const asUtc = Date.UTC(p.year, p.month - 1, p.day, p.hour, p.minute, p.second);
  return asUtc - Math.floor(at / 1000) * 1000;
}

/**
 * The instant at which the wall clock in `tz` shows the given local time.
 * A time that does not exist (spring-forward gap) resolves to the instant
 * after the gap; an ambiguous one (fall-back) to the earlier instant.
 */
export function zonedToUtc(
  year: number,
  month: number,
  day: number,
  hour: number,
  minute: number,
  tz: string,
): Date {
  const guess = Date.UTC(year, month - 1, day, hour, minute);
  // The offsets in force half a day before and after cover any transition that night.
  const candidates = [
    ...new Set([
      guess - zoneOffsetMs(guess - 43_200_000, tz),
      guess - zoneOffsetMs(guess + 43_200_000, tz),
    ]),
  ];
  const matches = candidates.filter((ms) => {
    const p = localParts(ms, tz);
    return (
      p.year === year &&
      p.month === month &&
      p.day === day &&
      p.hour === hour &&
      p.minute === minute
    );
  });
  // Ambiguous (fall back): the earlier instant. Non-existent (spring forward): after the gap.
  return new Date(matches.length ? Math.min(...matches) : Math.max(...candidates));
}

/** YYYY-MM-DD of an instant in `tz`. */
export function localDate(at: Date | number, tz: string): string {
  const p = localParts(at, tz);
  return `${p.year}-${pad(p.month)}-${pad(p.day)}`;
}

/** YYYY-MM-DDTHH:MM:SS (no offset) of an instant in `tz` — Graph's dateTimeTimeZone.dateTime. */
export function localDateTime(at: Date | number, tz: string): string {
  const p = localParts(at, tz);
  return `${localDate(at, tz)}T${pad(p.hour)}:${pad(p.minute)}:${pad(p.second)}`;
}

/** The instant of local midnight of a YYYY-MM-DD date in `tz`. */
export function midnight(date: string, tz: string): Date {
  const [y, m, d] = date.split('-').map(Number) as [number, number, number];
  return zonedToUtc(y, m, d, 0, 0, tz);
}

/** Adds whole days to a local date (calendar arithmetic, not 24 h). */
export function addDays(date: string, days: number): string {
  const [y, m, d] = date.split('-').map(Number) as [number, number, number];
  const t = new Date(Date.UTC(y, m - 1, d + days));
  return `${t.getUTCFullYear()}-${pad(t.getUTCMonth() + 1)}-${pad(t.getUTCDate())}`;
}

export const pad = (n: number) => String(n).padStart(2, '0');

/** "HH:MM" → minutes after midnight. */
export function hhmm(value: string): number {
  const [h, m] = value.split(':').map(Number) as [number, number];
  return h * 60 + m;
}

