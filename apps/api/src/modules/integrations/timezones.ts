/** IANA name for a Windows zone id; an IANA name passes through; unknown → null. */
export function windowsToIana(name: string | null | undefined): string | null {
  if (!name) return null;
  const mapped = WINDOWS_TO_IANA[name];
  if (mapped) return mapped;
  if (name === 'tzone://Microsoft/Utc') return 'Etc/UTC';
  try {
    new Intl.DateTimeFormat('en-US', { timeZone: name });
    return name;
  } catch {
    return null;
  }
}
